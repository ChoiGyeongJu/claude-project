/**
 * DART는 가운뎃점을 통일해서 쓰지 않는다. 흔한 변형들을 한 코드포인트로 모은다.
 * 실제로 관측되는 것은 U+00B7(MIDDLE DOT)과 U+318D(HANGUL LETTER ARAEA, "ㆍ")
 * 두 종류이지만, 흔히 섞여 들어오는 다른 가운뎃점류(아래아 조합자, 전각/반각 등)도
 * 방어적으로 포함한다.
 */
const MIDDLE_DOTS = /[·ㆍᆞ･‧•・]/g

/**
 * 제목 비교의 기준 표현을 만든다. 키워드·노이즈패턴·정기보고서패턴·정정접두어 —
 * 제목과 비교되는 모든 것이 이 함수를 통과한 뒤에 비교되어야 한다.
 *
 * 순서가 중요하다: 가운뎃점 치환을 반드시 NFKC 정규화보다 먼저 실행해야 한다.
 * NFKC가 U+318D(ㆍ, 한글 자모 아래아)를 U+119E(한글 모음 자모)로 매핑해버려서,
 * 정규화를 먼저 돌리면 이 정규식이 더 이상 그 문자를 찾지 못하고 U+00B7과
 * 영영 통합되지 않는다. 실제 데이터로 검증하다가 이 순서를 반대로 했다가
 * 한 시간을 날렸다 — 이 순서를 바꾸지 말 것.
 */
export function canonicalizeTitle(s: string): string {
  return s.replace(MIDDLE_DOTS, '·').normalize('NFKC').replace(/\s+/g, '')
}
